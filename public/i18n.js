const TRANSLATED_ATTRIBUTES = Object.freeze(['placeholder', 'aria-label', 'data-help', 'data-tooltip', 'title', 'alt', 'aria-valuetext']);
const JAPANESE = /[぀-ヿ㐀-鿿]/;
const textOriginals = new WeakMap();
const attributeOriginals = new WeakMap();
let currentLanguage = 'ja';
let observer = null;

function lookup(text) {
  return Object.prototype.hasOwnProperty.call(EN, text) ? EN[text] : null;
}

export function translate(text, language = currentLanguage) {
  if (language !== 'en' || typeof text !== 'string') return text;
  const core = text.trim();
  if (!core || !JAPANESE.test(core)) return text;
  let translated = lookup(core);
  if (translated === null) {
    for (const [pattern, build] of PATTERNS) {
      const match = core.match(pattern);
      if (match) { translated = build(match, lookup); if (translated) break; }
    }
  }
  if (!translated) return text;
  const leading = text.slice(0, text.indexOf(core));
  const trailing = text.slice(text.indexOf(core) + core.length);
  return `${leading}${translated}${trailing}`;
}

function translateTextNode(node) {
  const parent = node.parentElement;
  if (!parent || parent.closest('script, style, pre, [data-no-translate]')) return;
  const value = node.data;
  const translated = translate(value, 'en');
  if (translated === value) return;
  textOriginals.set(node, { ja: value, en: translated });
  node.data = translated;
}

function translateAttributes(element) {
  if (element.closest('[data-no-translate]')) return;
  for (const name of TRANSLATED_ATTRIBUTES) {
    const value = element.getAttribute(name);
    if (!value) continue;
    const translated = translate(value, 'en');
    if (translated === value) continue;
    const originals = attributeOriginals.get(element) || new Map();
    originals.set(name, { ja: value, en: translated });
    attributeOriginals.set(element, originals);
    element.setAttribute(name, translated);
  }
}

function translateTree(root) {
  if (!root) return;
  if (root.nodeType === Node.TEXT_NODE) { translateTextNode(root); return; }
  if (root.nodeType !== Node.ELEMENT_NODE) return;
  translateAttributes(root);
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    if (node.nodeType === Node.TEXT_NODE) translateTextNode(node);
    else translateAttributes(node);
  }
}

function restoreTree(root) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
  for (let node = walker.currentNode; node; node = walker.nextNode()) {
    if (node.nodeType === Node.TEXT_NODE) {
      const original = textOriginals.get(node);
      if (original && node.data === original.en) node.data = original.ja;
      textOriginals.delete(node);
    } else {
      const originals = attributeOriginals.get(node);
      if (!originals) continue;
      for (const [name, value] of originals) if (node.getAttribute(name) === value.en) node.setAttribute(name, value.ja);
      attributeOriginals.delete(node);
    }
  }
}

function startObserver() {
  if (observer) return;
  observer = new MutationObserver((mutations) => {
    if (currentLanguage !== 'en') return;
    for (const mutation of mutations) {
      if (mutation.type === 'childList') mutation.addedNodes.forEach(translateTree);
      else if (mutation.type === 'characterData') translateTextNode(mutation.target);
      else if (mutation.type === 'attributes') translateAttributes(mutation.target);
    }
  });
  observer.observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: [...TRANSLATED_ATTRIBUTES] });
}

export function applyLanguage(language) {
  currentLanguage = language === 'en' ? 'en' : 'ja';
  document.documentElement.lang = currentLanguage;
  if (currentLanguage === 'en') {
    translateTree(document.head.querySelector('title'));
    translateTree(document.body);
    startObserver();
  } else {
    restoreTree(document.body);
  }
}

export function currentUiLanguage() {
  return currentLanguage;
}
